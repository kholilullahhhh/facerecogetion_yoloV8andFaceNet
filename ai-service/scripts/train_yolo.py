# -*- coding: utf-8 -*-
"""Fine-tune YOLOv8s on datasets/yolo (single class: face).

- Data already split: images/{train,val} + labels/{train,val} (196 / 51),
  letterboxed 640x640, labels auto-generated by YuNet.
- 4 background images (empty label files) act as negatives.
- Starts from ../yolov8s.pt (COCO pretrained; head is rebuilt for 1 class).
- CPU only, small batch (RAM-constrained host).
- On success copies weights/best.pt ->  ../weights/yolov8s.pt  (production path).

Run:  python scripts/train_yolo.py   (from ai-service/)
"""
import json
import shutil
import time
from pathlib import Path

from ultralytics import YOLO

HERE = Path(__file__).resolve().parent
BASE = HERE.parent
DATA = BASE.parent / "datasets" / "yolo"
OUT = BASE / "training_runs" / ("yolo_" + time.strftime("%Y%m%d_%H%M%S"))
OUT.mkdir(parents=True, exist_ok=True)

DATA_YAML = OUT / "data_face.yaml"
DATA_YAML.write_text(
    f"path: {DATA.as_posix()}\n"
    "train: images/train\n"
    "val: images/val\n"
    "names:\n"
    "  0: face\n",
    encoding="utf-8",
)

EPOCHS = 20
PATIENCE = 8
BATCH = 4
IMGSZ = 640


def main():
    model = YOLO(str(BASE / "yolov8s.pt"))
    model.add_callback("on_train_epoch_end", epoch_printer)

    model.train(
        data=str(DATA_YAML),
        epochs=EPOCHS,
        patience=PATIENCE,
        batch=BATCH,
        imgsz=IMGSZ,
        device="cpu",
        workers=0,
        seed=42,
        project=str(OUT),
        name="run",
        verbose=False,
    )

    run_dir = OUT / "run"
    best = run_dir / "weights" / "best.pt"
    assert best.exists(), "training finished but best.pt missing"

    # parse final metrics from results.csv
    metrics = {}
    csv = run_dir / "results.csv"
    if csv.exists():
        lines = [l.strip() for l in csv.read_text().splitlines() if l.strip()]
        header = lines[0].split(",") if lines else []
        # best row = last epoch (ultralytics saves best.pt by mAP; last row ~= final/best)
        vals = lines[-1].split(",")
        for k, v in zip(header, vals):
            metrics[k.strip()] = v.strip()

    summary = {
        "epochs_requested": EPOCHS,
        "imgsz": IMGSZ,
        "batch": BATCH,
        "metrics_last_row": metrics,
    }
    with open(OUT / "yolo_train_metrics.json", "w") as f:
        json.dump(summary, f, indent=2)

    prod = BASE / "weights" / "yolov8s.pt"
    shutil.copy2(best, prod)
    print(f"[save] production YOLO -> {prod}")
    print("[done] run dir:", run_dir)
    for k in ("metrics/precision(B)", "metrics/recall(B)", "metrics/mAP50(B)", "metrics/mAP50-95(B)"):
        if k in metrics:
            print(f"  {k}: {metrics[k]}")


def epoch_printer(trainer):
    e = trainer.epoch + 1
    try:
        speed = ""
        t = trainer.tloss
        if t is not None:
            speed = f" loss={float(t.mean()):.4f}"
    except Exception:
        pass
    print(f"[yolo epoch {e:02d}{speed}]", flush=True)


if __name__ == "__main__":
    main()
